import { CheckCircle2, CircleHelp, XCircle } from 'lucide-react';
import type { DataBundle } from '../types';
import { useApp } from '../hooks/useApp';
import { runChecks } from '../utils/verification';
import { Card, Notice, PageHead, StatusBadge } from '../components/ui';
import { fmt } from '../utils/calc';

const DEMONSTRATED = [
  'Improved modelled boost availability', 'Reduced repeated high-current duty on the 12 V battery', 'Eco versus Power operating differences',
  'Cold-start effects', 'Capacitor pre-charge behaviour', 'Battery handover during long stops', 'Estimated regenerative energy recovery', 'Operating-voltage behaviour of the bank',
];
const UNPROVEN = [
  'Actual generator regenerative capability', 'Motor and controller temperature during repeated boosts', 'Battery degradation and lifetime', 'True production hardware cost',
  'Real road-load and engine-fuel maps', 'Lead-acid battery degradation during parking', 'Capacitor leakage at Indian operating temperatures',
  'Physical effectiveness of the pre-charge circuit', 'Controller redesign cost', "Real boost requests generated by the rider's throttle",
];
const INTEGRITY = [
  'A backward-facing energy approach: the speed trace sets the power, not a rider model', 'One-second simulation steps: current peaks inside a second are not seen',
  'Simplified engine characteristics: a straight-line fuel model, not a measured map', 'Assumed battery acceptance: 34, 68 and 120 W are a sweep, not data',
  'Assumed motor and generator efficiencies: 80% and 85%', 'Assumed engine warm-up dynamics: thermal mass, heat share and cooling are estimates',
  'Assumed ultracapacitor leakage: 1 mA per cell, from a datasheet figure at rated voltage',
];

export default function Validation() {
  const data = useApp((s) => s.data)!;
  const checks = runChecks(data);
  const passed = checks.filter((c) => c.pass).length;
  const groups = [...new Set(checks.map((c) => c.group))];
  return (
    <div className="space-y-4">
      <PageHead title="Engineering Validation" subtitle="What the simulation supports, what it does not, and what must be tested before production integration" />
      <div className="grid grid-cols-12 gap-3">
        <Card className="col-span-12 lg:col-span-6" title="A · Demonstrated in simulation" right={<StatusBadge status="sim" />}>
          <ul className="space-y-1.5 text-[13px]">{DEMONSTRATED.map((d) => <li key={d} className="flex gap-2"><CheckCircle2 size={15} className="text-ok shrink-0 mt-0.5" />{d}</li>)}</ul>
          <p className="text-xs text-muted mt-2">Demonstrated means the model produces it under the stated assumptions. None of it has been measured on a motorcycle.</p>
        </Card>
        <Card className="col-span-12 lg:col-span-6" title="B · Remains unproven" right={<StatusBadge status="assumed" />}>
          <ul className="space-y-1.5 text-[13px]">{UNPROVEN.map((d) => <li key={d} className="flex gap-2"><CircleHelp size={15} className="text-regen shrink-0 mt-0.5" />{d}</li>)}</ul>
        </Card>
      </div>

      <Card title="C · Technology alternatives" right={<StatusBadge status="sim" />} pad={false}><Alternatives data={data} /></Card>

      <div className="grid grid-cols-12 gap-3">
        <Card className="col-span-12 lg:col-span-6" title="D · Commercial feasibility" right={<StatusBadge status="assumed" />}>
          <table className="w-full text-[13px]"><tbody>
            {([['Capacitor cells (10 × 350 F)', 'about ₹3,550', 'retail estimate'], ['Installed system', 'about ₹5,000', 'preliminary assumption'],
              ['Converter', 'pending', 'not costed'], ['Controller redesign for 25 V', 'pending', 'not costed'], ['Protection and enclosure', 'pending', 'not costed'],
              ['Battery replacement savings', 'not yet validated', 'needs battery life data'], ['Payback period', 'not claimed', 'no verified figure']] as [string, string, string][]).map(([a, b, c]) => (
              <tr key={a} className="border-b border-line/60"><td className="py-1.5">{a}</td><td className="py-1.5 text-right num font-semibold">{b}</td><td className="py-1.5 pl-3 text-xs text-muted">{c}</td></tr>))}
          </tbody></table>
          <div className="mt-3"><Notice tone="warn">The modelled fuel gain over stock iGO Assist is well under 1%, so fuel alone does not pay for the system. The case rests on boost availability and battery duty, and battery-life benefit is untested.</Notice></div>
        </Card>
        <Card className="col-span-12 lg:col-span-6" title="E · Simulation integrity" right={<StatusBadge status="assumed" />}>
          <ul className="space-y-1.5 text-[13px] list-disc pl-4">{INTEGRITY.map((d) => <li key={d}>{d}</li>)}</ul>
          <p className="text-xs text-muted mt-2">These are engineering assumptions, not measured facts. Absolute fuel economy is not calibrated: read differences between cases, not the km/L values themselves.</p>
          <div className="mt-2"><Notice tone="warn">Known model and specification mismatch: Power mode has stop-start off in the specification but on in the current simulation case, so its fuel and engine-off figures are optimistic.</Notice></div>
        </Card>
      </div>

      <Card title={<>Verification tests on the loaded data · {passed}/{checks.length} passed</>} right={<StatusBadge status="calc" />} pad={false}>
        <div className="grid md:grid-cols-2">
          {groups.map((g) => (
            <div key={g} className="border-b md:border-r border-line/60 p-3">
              <h4 className="h-tech uppercase text-sm mb-1">{g}</h4>
              <table className="w-full text-[13px]"><tbody>
                {checks.filter((c) => c.group === g).map((c) => (
                  <tr key={c.name}><td className="py-0.5 w-5">{c.pass ? <CheckCircle2 size={14} className="text-ok" /> : <XCircle size={14} className="text-denied" />}</td>
                    <td className="py-0.5">{c.name}</td><td className="py-0.5 text-right num text-muted">expected {c.expected}</td><td className="py-0.5 text-right num font-semibold w-20">{c.actual}</td></tr>))}
              </tbody></table>
            </div>))}
        </div>
        <p className="px-3 py-2 text-xs text-muted">These checks run in the browser against whatever data is loaded, including imported files. The same checks run in the test suite (<code>npm test</code>).</p>
      </Card>
    </div>
  );
}

function Alternatives({ data }: { data: DataBundle }) {
  const w = data.warm.scenarios; const s = (id: string) => w[id]?.summary;
  const fr = (id: string) => { const x = s(id); return x ? `${x.full}/${x.requests}` : 'no data'; };
  const stock = ['B1', 'B2', 'B3'].map(s).filter(Boolean) as NonNullable<ReturnType<typeof s>>[];
  const range = (f: (x: NonNullable<ReturnType<typeof s>>) => number) => `${Math.min(...stock.map(f))}–${Math.max(...stock.map(f))}`;
  const base = s('B2')?.fuelMl ?? null;
  const gain = (id: string) => { const f = s(id)?.fuelMl ?? null; return base && f ? `${(((base - f) / base) * 100).toFixed(1)}%` : 'no data'; };
  const cold = data.cold.scenarios; const cfr = (k: string) => (cold[k] ? `${cold[k].cold.full}/${cold[k].cold.requests}` : 'no data');
  const NT = 'Not tested'; const NS = 'Not simulated';
  const rows: [string, string, string, string, string, string][] = [
    ['Boosts in full, warm WMTC', stock.length ? `${range((x) => x.full)} of 9` : 'no data', NS, fr('F'), fr('C'), `${fr('D')} Eco · ${fr('DP')} Power`],
    ['High-current battery pulses per 600 s', stock.length ? range((x) => x.batteryPulses ?? 0) : 'no data', NS, 'supplies every pulse itself', String(s('C')?.batteryPulses ?? 'no data'), String(s('D')?.batteryPulses ?? 'no data')],
    ['Fuel against stock (68 W case)', 'baseline', NS, gain('F'), gain('C'), gain('D')],
    ['Boosts in full, cold pass', `${cfr('B1_stock')} to ${cfr('B3_stock')}`, NS, NS, NS, `${cfr('D_park_12h')} overnight`],
    ['Cycle life under pulse duty', NT, NT, NT, NT, NT],
    ['Behaviour in heat beside the engine', NT, NT, NT, NT, NT],
    ['Installed cost', 'in production', 'not costed', 'not costed', 'not costed', 'about ₹5,000 assumed'],
    ['Hardware built', 'in production', 'no', 'no', 'no', 'no'],
  ];
  const cls = (v: string) => (v === NT || v === NS || v === 'no' || v.startsWith('not ') ? 'text-muted italic' : 'num');
  return (
    <div>
      <table className="w-full text-[13px]">
        <thead><tr className="bg-soft text-muted text-left border-b border-line"><th className="px-4 py-2 font-medium">Criterion</th><th className="px-3 py-2 font-medium">Existing lead-acid</th>
          <th className="px-3 py-2 font-medium">Higher-power lead-acid</th><th className="px-3 py-2 font-medium">High-power lithium 12 V</th><th className="px-3 py-2 font-medium">CapAssist Option X</th><th className="px-3 py-2 font-medium">CapAssist Option Y</th></tr></thead>
        <tbody>{rows.map((r) => <tr key={r[0]} className="border-b border-line/60"><td className="px-4 py-1.5">{r[0]}</td>{r.slice(1).map((v, k) => <td key={k} className={`px-3 py-1.5 ${cls(v)}`}>{v}</td>)}</tr>)}</tbody>
      </table>
      <p className="px-4 py-2 text-xs text-muted">Figures are simulation outputs read from the data files. Fuel difference for the lithium case: {fmt(s('F')?.kmPerL ?? null, 1)} km/L against {fmt(s('D')?.kmPerL ?? null, 1)} km/L for CapAssist Y Eco. "Not tested" means there is no evidence either way.</p>
    </div>
  );
}
